import { describe, it, expect } from 'vitest';
import {
  countWords,
  countCharacters,
  humanizeRequestSchema,
  feedbackSchema,
  DOCUMENT_TYPES,
  FEEDBACK_CATEGORIES,
} from '../shared/schemas.ts';

describe('Shared Schemas & Utilities (V3)', () => {
  describe('Word and Character Counting', () => {
    it('accurately counts words with varied whitespace', () => {
      expect(countWords('')).toBe(0);
      expect(countWords('   ')).toBe(0);
      expect(countWords('Hello world')).toBe(2);
      expect(countWords('  Natural,   expressive\nwriting\tflow.  ')).toBe(4);
    });

    it('accurately counts characters', () => {
      expect(countCharacters('')).toBe(0);
      expect(countCharacters('Hello')).toBe(5);
      expect(countCharacters('Hello world')).toBe(11);
    });
  });

  describe('humanizeRequestSchema', () => {
    it('validates a complete, valid humanize request with V3 fields', () => {
      const validReq = {
        text: 'This is a sample sentence generated by an automated system.',
        tone: 'professional',
        audience: 'general',
        strength: 'balanced',
        documentType: 'academic_abstract',
        voicePreferences: {
          formality: 'formal',
          directness: 'direct',
          conciseness: 'concise',
          technicalDepth: 'expert',
        },
        preserveStructure: true,
        userIntent: 'Summarize key findings without defensive language.',
        protectedTerms: ['PostgreSQL', 'GDPR'],
        promptVersion: 'v3',
      };

      const result = humanizeRequestSchema.safeParse(validReq);
      expect(result.success).toBe(true);
      if (result.success) {
        expect(result.data.tone).toBe('professional');
        expect(result.data.documentType).toBe('academic_abstract');
        expect(result.data.voicePreferences?.formality).toBe('formal');
        expect(result.data.promptVersion).toBe('v3');
      }
    });

    it('defaults documentType to general_prose and promptVersion to v3', () => {
      const basicReq = {
        text: 'Clean text',
        tone: 'conversational',
        audience: 'general',
        strength: 'light',
      };

      const result = humanizeRequestSchema.safeParse(basicReq);
      expect(result.success).toBe(true);
      if (result.success) {
        expect(result.data.documentType).toBe('general_prose');
        expect(result.data.promptVersion).toBe('v3');
      }
    });

    it('validates all 9 document types', () => {
      for (const docType of DOCUMENT_TYPES) {
        const req = {
          text: 'Document sample text',
          tone: 'professional',
          audience: 'general',
          strength: 'balanced',
          documentType: docType,
        };
        const result = humanizeRequestSchema.safeParse(req);
        expect(result.success).toBe(true);
      }
    });

    it('rejects empty text and whitespace-only text', () => {
      const invalidEmpty = {
        text: '',
        tone: 'professional',
        audience: 'general',
        strength: 'balanced',
      };
      expect(humanizeRequestSchema.safeParse(invalidEmpty).success).toBe(false);

      const invalidWhitespace = {
        text: '   \n\t  ',
        tone: 'professional',
        audience: 'general',
        strength: 'balanced',
      };
      expect(humanizeRequestSchema.safeParse(invalidWhitespace).success).toBe(false);
    });

    it('rejects invalid tone values', () => {
      const invalidReq = {
        text: 'Sample text',
        tone: 'alien_voice',
        audience: 'general',
        strength: 'balanced',
      };

      const result = humanizeRequestSchema.safeParse(invalidReq);
      expect(result.success).toBe(false);
    });
  });

  describe('feedbackSchema', () => {
    it('validates all diagnostic feedback categories', () => {
      for (const cat of FEEDBACK_CATEGORIES) {
        const validFeedback = {
          rating: 4,
          category: cat,
          comment: `Feedback for ${cat}`,
        };
        const result = feedbackSchema.safeParse(validFeedback);
        expect(result.success).toBe(true);
      }
    });

    it('rejects invalid rating numbers', () => {
      const invalid = {
        rating: 10,
        category: 'quality',
      };

      const result = feedbackSchema.safeParse(invalid);
      expect(result.success).toBe(false);
    });
  });
});
